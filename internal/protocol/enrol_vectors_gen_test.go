// enrol.json follows the control plane's enrolment vectors byte for byte:
// same seeds, nonce key and clock, and the same JSON layout.

const enrolNote = "TEST ONLY. Every key in this file is derived from a published seed; never use these keys outside tests. Generated by seawise-platform apps/api/src/test/fixtures/enrol-vectors.ts."

const (
	enrolPublic  = "https://api.seawise.io"
	enrolURL     = enrolPublic + "/device/v2/enroll"
	enrolNowMS   = int64(1_800_000_000_000)
	enrolServer  = "6f1d2c3b-4a59-4687-9a1b-2c3d4e5f6a7b"
	enrolOther   = "7a6b5c4d-3e2f-4a1b-8c9d-0e1f2a3b4c5d"
	enrolDevice  = "d0000000-0000-4000-8000-000000000001"
	enrolBoot    = "0c0c0c0c-0000-4000-8000-000000000001"
	enrolJTI     = "enrol-vector-jti-000000001"
	enrolIAT     = int64(1_800_000_000)
	enrolNonceMS = 16
)

var enrolKeyNames = []string{"enrol-new", "enrol-registered"}

type enrolKeyInfo struct {
	Name string `json:"name"`
	Seed string `json:"seed"`
	X    string `json:"x"`
	KID  string `json:"kid"`
}

type enrolInput struct {
	DPoP     string  `json:"dpop"`
	FRPToken *string `json:"frp_token"`
	Body     string  `json:"body"`
}

type enrolServerCtx struct {
	ID          string `json:"id"`
	TokenSHA256 string `json:"token_sha256"`
}

type enrolContext struct {
	Method         string         `json:"method"`
	URL            string         `json:"url"`
	NowMS          int64          `json:"now_ms"`
	NonceKey       string         `json:"nonce_key"`
	Server         enrolServerCtx `json:"server"`
	RegisteredKIDs []string       `json:"registered_kids"`
	Seen           []seenJTI      `json:"seen"`
}

type enrolOK struct {
	Result   string `json:"result"`
	ServerID string `json:"server_id"`
	DeviceID string `json:"device_id"`
	KeyID    string `json:"key_id"`
}

type enrolErr struct {
	Error string `json:"error"`
	Code  string `json:"code,omitempty"`
}

type enrolWire struct {
	Status int `json:"status"`
	Body   any `json:"body"`
}

type enrolCase struct {
	Name    string       `json:"name"`
	Input   enrolInput   `json:"input"`
	Context enrolContext `json:"context"`
	Expect  string       `json:"expect"`
	Wire    enrolWire    `json:"wire"`
}

type enrolFile struct {
	Format string         `json:"format"`
	Note   string         `json:"note"`
	Keys   []enrolKeyInfo `json:"keys"`
	Cases  []enrolCase    `json:"cases"`
}

func enrolNonce(key []byte, nowMS int64) string {
	var issued [4]byte
	binary.BigEndian.PutUint32(issued[:], uint32(nowMS/1000))
	body := "n1." + b64Encode(issued[:])
	m := hmac.New(sha256.New, key)
	m.Write([]byte(body))
	return body + "." + b64Encode(m.Sum(nil)[:enrolNonceMS])
}

func enrolTokenHex(label string) string {
	d := sha256.Sum256([]byte(label))
	return hex.EncodeToString(d[:])
}

type enrolProofOpts struct{ htu, htm, nonce, bodyFor string }

func enrolProof(priv ed25519.PrivateKey, body string, o enrolProofOpts) string {
	nonceKey := bytes.Repeat([]byte{7}, 32)
	c := DPoPClaims{JTI: enrolJTI, HTM: "POST", HTU: enrolURL, IAT: enrolIAT, Nonce: enrolNonce(nonceKey, enrolNowMS), BodySHA256: BodyDigest([]byte(body))}
	if o.htu != "" {
		c.HTU = o.htu
	}
	if o.htm != "" {
		c.HTM = o.htm
	}
	if o.nonce != "" {
		c.Nonce = o.nonce
	}
	if o.bodyFor != "" {
		c.BodySHA256 = BodyDigest([]byte(o.bodyFor))
	}
	t, err := signJWS(priv, TypDPoP, true, c)
	if err != nil {
		panic(err)
	}
	return t
}

func genEnrol() enrolFile {
	neu, reg := vecKey("enrol-new"), vecKey("enrol-registered")
	token := enrolTokenHex("seawise enrol vector v1 token")
	other := enrolTokenHex("seawise enrol vector other token")
	upper := strings.ToUpper(token)
	nonceKey := bytes.Repeat([]byte{7}, 32)
	tokenHash := sha256.Sum256([]byte(token))

	body := `{"server_id":"` + enrolServer + `"}`
	bodyBoot := `{"server_id":"` + enrolServer + `","boot_id":"` + enrolBoot + `"}`
	dup := `{"server_id":"` + enrolServer + `","server_id":"` + enrolServer + `"}`
	upperBody := `{"server_id":"` + strings.ToUpper(enrolServer) + `"}`
	big := strings.Replace(bodyBoot, "{", "{"+strings.Repeat(" ", 200), 1)
	otherBody := `{"server_id":"` + enrolOther + `"}`
	extra := `{"server_id":"` + enrolServer + `","name":"x"}`

	ctx := func(mut func(*enrolContext)) enrolContext {
		c := enrolContext{
			Method: "POST", URL: enrolURL, NowMS: enrolNowMS, NonceKey: hex.EncodeToString(nonceKey),
			Server:         enrolServerCtx{ID: enrolServer, TokenSHA256: hex.EncodeToString(tokenHash[:])},
			RegisteredKIDs: []string{vecKID("enrol-registered")}, Seen: []seenJTI{},
		}
		if mut != nil {
			mut(&c)
		}
		return c
	}
	ok := func(name string) enrolWire {
		return enrolWire{200, enrolOK{"enrolled", enrolServer, enrolDevice, vecKID(name)}}
	}
	tokenErr := enrolWire{401, enrolErr{Error: "invalid_token"}}
	malformed := enrolWire{400, enrolErr{"invalid_request", "malformed"}}
	bad := func(code string) enrolWire { return enrolWire{401, enrolErr{"invalid_proof", code}} }
	nonceErr := enrolWire{401, enrolErr{"use_dpop_nonce", "use_dpop_nonce"}}
	in := func(dpop string, tok *string, b string) enrolInput { return enrolInput{dpop, tok, b} }
	c := func(name string, i enrolInput, expect string, w enrolWire, cx enrolContext) enrolCase {
		return enrolCase{name, i, cx, expect, w}
	}
	none := enrolProofOpts{}

	cases := []enrolCase{
		c("valid", in(enrolProof(neu, body, none), &token, body), "ok", ok("enrol-new"), ctx(nil)),
		c("valid-with-boot-id", in(enrolProof(neu, bodyBoot, none), &token, bodyBoot), "ok", ok("enrol-new"), ctx(nil)),
		c("wrong-token", in(enrolProof(neu, body, none), &other, body), "invalid_token", tokenErr, ctx(nil)),
		c("retired-token", in(enrolProof(neu, body, none), &token, body), "invalid_token", tokenErr,
			ctx(func(c *enrolContext) { c.Server.TokenSHA256 = strings.Repeat("0", 64) })),
		c("malformed-token", in(enrolProof(neu, body, none), &upper, body), "invalid_token", tokenErr, ctx(nil)),
		c("missing-token", in(enrolProof(neu, body, none), nil, body), "invalid_token", tokenErr, ctx(nil)),
		c("other-server", in(enrolProof(neu, otherBody, none), &token, otherBody), "invalid_token", tokenErr, ctx(nil)),
		c("replayed", in(enrolProof(neu, body, none), &token, body), "replayed", bad("replayed"),
			ctx(func(c *enrolContext) { c.Seen = []seenJTI{{KID: vecKID("enrol-new"), JTI: enrolJTI}} })),
		c("stale-nonce", in(enrolProof(neu, body, enrolProofOpts{nonce: enrolNonce(nonceKey, enrolNowMS-300_000)}), &token, body), "bad_nonce", nonceErr, ctx(nil)),
		c("foreign-nonce", in(enrolProof(neu, body, enrolProofOpts{nonce: enrolNonce(bytes.Repeat([]byte{8}, 32), enrolNowMS)}), &token, body), "bad_nonce", nonceErr, ctx(nil)),
		c("wrong-htu", in(enrolProof(neu, body, enrolProofOpts{htu: enrolPublic + "/device/v2/identity"}), &token, body), "wrong_htu", bad("wrong_htu"), ctx(nil)),
		c("wrong-htm", in(enrolProof(neu, body, enrolProofOpts{htm: "PUT"}), &token, body), "wrong_htm", bad("wrong_htm"), ctx(nil)),
		c("body-tampered", in(enrolProof(neu, body, enrolProofOpts{bodyFor: bodyBoot}), &token, body), "body_mismatch", bad("body_mismatch"), ctx(nil)),
		c("duplicate-member", in(enrolProof(neu, dup, none), &token, dup), "malformed", malformed, ctx(nil)),
		c("unknown-member", in(enrolProof(neu, extra, none), &token, extra), "malformed", malformed, ctx(nil)),
		c("upper-case-uuid", in(enrolProof(neu, upperBody, none), &token, upperBody), "malformed", malformed, ctx(nil)),
		c("oversize-body", in(enrolProof(neu, big, none), &token, big), "malformed", malformed, ctx(nil)),
		c("key-registered-before", in(enrolProof(reg, body, none), &token, body), "bad_key", enrolWire{400, enrolErr{"invalid_key", "bad_key"}}, ctx(nil)),
	}
	keys := make([]enrolKeyInfo, 0, len(enrolKeyNames))
	for _, n := range enrolKeyNames {
		keys = append(keys, enrolKeyInfo{Name: n, Seed: hex.EncodeToString(vecKey(n).Seed()), X: vecX(n), KID: vecKID(n)})
	}
	return enrolFile{Format: "enrol", Note: enrolNote, Keys: keys, Cases: cases}
}

func marshalEnrol(f enrolFile) []byte {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(f); err != nil {
		panic(err)
	}
	return buf.Bytes()
}
